void delay_us(uint16_t delay)
{
	uint16_t start = TIM6->CNT;
	uint16_t now = start;

	while ((uint16_t)(now-start) < delay) {
		now = TIM6->CNT;
	}
}

// Reading the OneWire line`s state
static bool read_line(GPIO_TypeDef* gpio, uint16_t pin)
{
	return HAL_GPIO_ReadPin(gpio, pin) == GPIO_PIN_SET;
}

// Onewire Bus init. Returns true if the sensor was found
static bool ow_reset(void)
{
	HAL_GPIO_WritePin(GPIOC, DS18B20_Pin, GPIO_PIN_RESET);
	delay_us(480);

	HAL_GPIO_WritePin(GPIOC, DS18B20_Pin, GPIO_PIN_SET);
	delay_us(70);

	bool present = !read_line(GPIOC, DS18B20_Pin); // LOW = sensor found

	delay_us(410);
	return present;
}

// Write one bit
static void ow_write_bit(bool bit)
{
	HAL_GPIO_WritePin(GPIOC, DS18B20_Pin, GPIO_PIN_RESET);
	if (bit) {
		delay_us(5);
		HAL_GPIO_WritePin(GPIOC, DS18B20_Pin, GPIO_PIN_SET);
		delay_us(55);
	}
	else {
		delay_us(60);
		HAL_GPIO_WritePin(GPIOC, DS18B20_Pin, GPIO_PIN_SET);
		delay_us(5);
	}
}
// Read one bit
static bool ow_read_bit(void)
{
    HAL_GPIO_WritePin(GPIOC, DS18B20_Pin, GPIO_PIN_RESET);
    delay_us(3);

    HAL_GPIO_WritePin(GPIOC, DS18B20_Pin, GPIO_PIN_SET);
    delay_us(10);

    bool bit = read_line(GPIOC, DS18B20_Pin);

    delay_us(47);
    return bit;
}

// Write one byte
static void ow_write_byte(uint8_t byte)
{
	for (int i=0; i<8; i++) {
		ow_write_bit((byte >> i) & 1U == 1);
	}
}

// Read one byte
static uint8_t ow_read_byte(void)
{
	uint8_t byte = 0;
	for (int i = 0; i<8; i++){
		if (ow_read_bit()) {
			byte |= (uint8_t)(1U << i);
		}
	}
	return byte;
}

// Read scratchpad on the sensor
static bool read_scratchpad(uint8_t scratchpad[9]){
	if (!ow_reset()) return false;

	ow_write_byte(0xCC);
	ow_write_byte(0xBE);

	for (int i = 0; i < 9; i++) {
		scratchpad[i] = ow_read_byte();
	}
	return crc8(scratchpad, 8) == scratchpad[8];
}

// Measure the temperature
static bool read_temperature(int32_t *centi_c)
{
	if (!ow_reset()) return false;
	ow_write_byte(0xCC);
	ow_write_byte(0x44);

	HAL_Delay(750);

	uint8_t scratchpad[9];
	for (int attempt = 0; attempt < 3; attempt ++){
		if (read_scratchpad(scratchpad)) {
			int16_t raw = (int16_t)((scratchpad[1] << 8) | scratchpad[0]);
			*centi_c = ((int32_t)raw * 100) / 16;

			return true;
		}
		uart_printf("read_temperature retry\n\r");
	}
    uart_printf("temperature sensor did not answer\n\r");

   	return false;
}

